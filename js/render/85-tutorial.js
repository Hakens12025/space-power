    <p>把上面这些串起来，第一局大致是这样：按 <code class="key">Space</code> 让时间跑起来，拖一个框把三艘蓝舰全选上，在底栏点开 <code class="ui">火控</code>。接下来不必你动手，三艘舰会自己索敌，评分规则是火力缺口优先、距离次之，于是它们会一起压向最近的那个靶。</p>

