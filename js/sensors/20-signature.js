/* ============================================================================
   SN4 感知数值表。全库【唯一】一张感知常量表,名字沿用 SENS,住在这里。
   不许再出现第二张(PCP / SENS2 / 按舰种另立一张 之类)—— 两张表必然漂移,而漂移在这个
   系统里是完全静默的:数错了界面照样全绿。
   ----------------------------------------------------------------------------
   三条量程律的实现在 sensors/22-percep,本文件只提供它们的常数。改数只动这里。

   ---- SN6 改名(2026-09-19,值一个没动)----
   IR_REF / LIS_REF / ACT_REF -> IR_DET / LIS_DET / ACT_DET。这三个数语义上一直是【发现半径】
   ("多远能看见/听见/照到"),而 SN6 的误差椭圆内核要引入第二套半径 ——【定位精度尺度】,
   它决定椭圆多大。两套必须分家:精度律写成 σ_θ = TH0*(d/R)^k,R 一放大,每一个距离上的精度
   都跟着放大,于是"看得更远"和"算得更准"在单半径模型里是同一个旋钮。现实里这本来就是两部设备
   (对空搜索雷达 与 照射器)。腾出来的 *_REF 给定位尺度,住在 sensors/23-cov,由距离梯子反解写入。

   ---- 锚点推导(每一个常数都必须能回答"凭什么是这个数") ----
   size:体型,同时当光学红外底数与雷达反射基数。锚点 = 舰体结构 hp 的 2/3 次方
     (截面积 正比 体积^(2/3)):DD 550^(2/3)=67.0、CA 900^(2/3)=93.2,比值 0.719。
     旧模型手调出来的船体信号基数比值恰好是 0.70 —— 两条独立推导对上了,所以沿用 0.70/1.00。
   stealth:(0,1] 反射倍率,只乘雷达反射、不乘红外。沿用旧雷达截面的 DD 0.60 / CA 1.00
     (较新的小舰体做了外形处理)。注意与旧模型的口径差:旧雷达截面一个数里裹着体型与外形
     两件事,现在体型归 size、外形归 stealth,所以合成反射 DD = 0.70x0.60 = 0.42
     (旧 0.60),DD 相对更隐蔽 —— 这是"一个 size 两头都算"的刻意结果。
   emit / recv:雷达发射机与接收机的档次,无量纲。DD 定为基准 1.0(全库其它表也都拿 DD
     当基准档),CA 3.0 —— 取 3 而不是 2,是为了让 (emit x recv)^(1/4) = 9^(1/4) = 1.732
     把 CA 的照射量程抬到 260k,贴住 83-hud 一直在画的那个 250k 圈。
   ACT_DET = 150000:基准舰(emit=recv=1)对基准目标(反射 1.0)的照射量程。
     它同时就是 DD 那个圈的半径。旧模型这里是分裂的:UI 画 150k/250k,而回波门限
     1e-22 算出来的真实照射距离是 254k~316k —— 圈与判据从来就不是一个数,这次钉死成一个。
   LIS_DET = 600000:基准接收机听见一部基准发射机【照射中】的距离。
     取 600k 是为了保住"手电效应"的 4 倍差(自照 150k / 被听 600k)——
     这是整个信息战设计的灵魂:开雷达看得清,但先被别人听见。
     旧模型这个比值是 790k/254k = 3.1,量级一致。
   IR_DET = 180000:亮度 lum=1.0 的目标的光学可见半径。
     锚点:让静默熄火的 DD(lum=0.70)恰好在 150,598km 被看到 —— 与 DD 主炮射程 150k
     同一个数量级。含义是"一艘完全静默的船,要等到进了主炮射程才刚被光学发现",
     这正是隐蔽接近有意义的前提。CA 静默 = 180,000,旧模型 CA 静默是 182,574,几乎不动。
   P_ENG_MAIN=3.0 / P_ENG_SIDE=1.0:引擎是全船最大的耗电户。满推让亮度 x4、量程 x2。
     旧模型的引擎辐射常数 25 压在船体 0.7 上是 36 倍,等于"一点火就全场可见"(满推 DD 828k,
     比地图还大),这次刻意压到 2 倍量程 —— 让 size 真的说得上话。
   EMIT_P:发射机的功率档。同一张表既当【功耗】(进光学亮度)又当【射频响度】(进静听),
     因为它们物理上就是同一个量。silent 恒 0 = 绝对射频静默,旧模型那个船体射频泄漏系数
     船体泄漏(约 5 万公里的泄漏圈)已删 —— 热循环里"sigRF 非零"那道早退要真的省下东西,
     这一档就必须真的是 0。
   BEACON_*:信标 = 专职传感器荚舱。EMIT=RECV=4.0 ⇒ 照射量程 150000x16^(1/4) = 300,000,
     与全库既有的信标 300k 常数(旧 projVisibleTo / 83-hud)逐位相同。
   DEC/G:驻留衰减与按档增益。光学与静听 0.90,照射 0.94(手电端着不放,衰减慢)——
     两个数沿用旧内核。增益改成【按信噪比档查表】,因为旧式的 g x sqrt(SNR-1) 要在
     热路径上做开方,而分档本来就已经把信噪比量化过一遍了。
   ---- 一条不变量(SN5 补,数值一个没动) ----
   【被动先于主动,界划在主推档】:任一照方对任一【开着主推】的目标,照射量程必须小于该目标的光学可见半径。
   今天最薄的一格是信标照 CA/BB/CV(300,000 vs 360,000,余量 16.7%);舰对舰最薄的是 CA 照 CA(259,808 vs 360,000,余量 27.8%)。
   (信标照 DD 只有 241,510 —— 别忘了乘目标的合成反射 0.42;300,000 是对【标准目标】反射 1.0 那一档。)
   界【刻意不划在侧推档】:对一艘熄火静默的冷目标,主动大幅先于被动是本表的设计意图(见上面 IR_DET 那条),
   侧推是最弱的一档动力、几乎就是冷目标,那一段是过渡区。换成侧推界的话 CA 照 CA 会越界 5,249 km(2.1%)——
   这正是 FLOW53_RADAR ①b 拿来当反向对照的那一格,它证明这条判据不是随便什么数都能过。
   为一个 2.1% 的边界去砍雷达量程是杠杆用错了尺寸:实测把 CA 的收发乘积从 9 降到 4,
   靶场开局三个靶一个都照不到(需要乘积 >= 7.87),主炮一发都发不出来。
   (SN6 已删)接触阶梯的那几个阈值原封不动沿用过旧内核 —— 下游(武器门控 / 迷雾渲染)读的是
     lit 的 0/1/2/3,阶梯形状一变它们全要跟着调,那不是本轮的事。
   ========================================================================= */
