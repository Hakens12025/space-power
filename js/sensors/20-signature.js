/* ============================================================================
   SN4 感知数值表。全库【唯一】一张感知常量表,名字沿用 SENS,住在这里。
   不许再出现第二张(PCP / SENS2 / 按舰种另立一张 之类)—— 两张表必然漂移,而漂移在这个
   系统里是完全静默的:数错了界面照样全绿。
   ----------------------------------------------------------------------------
   三条量程律的实现在 sensors/22-percep,本文件只提供它们的常数。改数只动这里。

   ---- 锚点推导(每一个常数都必须能回答"凭什么是这个数") ----
   size:体型,同时当光学红外底数与雷达反射基数。锚点 = 舰体结构 hp 的 2/3 次方
     (截面积 正比 体积^(2/3)):DD 550^(2/3)=67.0、CA 900^(2/3)=93.2,比值 0.719。
     旧模型手调出来的船体信号基数比值恰好是 0.70 —— 两条独立推导对上了,所以沿用 0.70/1.00。
   stealth:(0,1] 反射倍率,只乘雷达反射、不乘红外。沿用旧雷达截面的 DD 0.60 / CA 1.00
     (较新的小舰体做了外形处理)。注意与旧模型的口径差:旧雷达截面一个数里裹着体型与外形
     两件事,现在体型归 size、外形归 stealth,所以合成反射 DD = 0.70x0.60 = 0.42
     (旧 0.60),DD 相对更隐蔽 —— 这是"一个 size 两头都算"的刻意结果。
   emit / recv:雷达发射机与接收机的档次,无量纲。DD 定为基准 1.0(全库其它表也都拿 DD
     当基准档),CA 3.0 —— 取 3 而不是 2,是为了让 (emit x recv)^(1/4) = 9^(1/4) = 1.732
     把 CA 的照射量程抬到 260k,贴住 83-hud 一直在画的那个 250k 圈。
   ACT_REF = 150000:基准舰(emit=recv=1)对基准目标(反射 1.0)的照射量程。
     它同时就是 DD 那个圈的半径。旧模型这里是分裂的:UI 画 150k/250k,而回波门限
     1e-22 算出来的真实照射距离是 254k~316k —— 圈与判据从来就不是一个数,这次钉死成一个。
   LIS_REF = 600000:基准接收机听见一部基准发射机【照射中】的距离。
     取 600k 是为了保住"手电效应"的 4 倍差(自照 150k / 被听 600k)——
     这是整个信息战设计的灵魂:开雷达看得清,但先被别人听见。
     旧模型这个比值是 790k/254k = 3.1,量级一致。
   IR_REF = 180000:亮度 lum=1.0 的目标的光学可见半径。
     锚点:让静默熄火的 DD(lum=0.70)恰好在 150,598km 被看到 —— 与 DD 主炮射程 150k
     同一个数量级。含义是"一艘完全静默的船,要等到进了主炮射程才刚被光学发现",
     这正是隐蔽接近有意义的前提。CA 静默 = 180,000,旧模型 CA 静默是 182,574,几乎不动。
   P_ENG_MAIN=3.0 / P_ENG_SIDE=1.0:引擎是全船最大的耗电户。满推让亮度 x4、量程 x2。
     旧模型的引擎辐射常数 25 压在船体 0.7 上是 36 倍,等于"一点火就全场可见"(满推 DD 828k,
     比地图还大),这次刻意压到 2 倍量程 —— 让 size 真的说得上话。
   EMIT_P:发射机的功率档。同一张表既当【功耗】(进光学亮度)又当【射频响度】(进静听),
     因为它们物理上就是同一个量。silent 恒 0 = 绝对射频静默,旧模型那个船体射频泄漏系数
     船体泄漏(约 5 万公里的泄漏圈)已删 —— 热循环里"sigRF 非零"那道早退要真的省下东西,
     这一档就必须真的是 0。
   BEACON_*:信标 = 专职传感器荚舱。EMIT=RECV=4.0 ⇒ 照射量程 150000x16^(1/4) = 300,000,
     与全库既有的信标 300k 常数(旧 projVisibleTo / 83-hud)逐位相同。
   DEC/G:驻留衰减与按档增益。光学与静听 0.90,照射 0.94(手电端着不放,衰减慢)——
     两个数沿用旧内核。增益改成【按信噪比档查表】,因为旧式的 g x sqrt(SNR-1) 要在
     热路径上做开方,而分档本来就已经把信噪比量化过一遍了。
   LIT 阶梯 / HYST / ACT_DOWN:阶梯阈值原封不动沿用旧内核 —— 下游(武器门控 / 迷雾渲染)读的是
     lit 的 0/1/2/3,阶梯形状一变它们全要跟着调,那不是本轮的事。
   ========================================================================= */
const SENS = {
  /* ---- 舰种行:四个字段取代旧的八个。ecmPower 不在替换之列,它是干扰强度不是感知量,搭这张表的车 ---- */
  CLS: {
    DD: { size: 0.70, stealth: 0.60, emit: 1.0, recv: 1.0, ecmPower: 0.3 }, // 巴黎级:小、低反射、基准雷达
    CA: { size: 1.00, stealth: 1.00, emit: 3.0, recv: 3.0, ecmPower: 0.5 }, // 马拉松级:大、无外形处理、大雷达
  },

  /* ---- 通道一 光学/红外(纯被动) ---- */
  IR_REF: 180000,      // lum=1.0 的光学可见半径 km
  P_ENG_MAIN: 3.0,     // 主推/反推的功耗档
  P_ENG_SIDE: 1.0,     // 侧推/姿态的功耗档
  EMIT_P: { silent: 0, paint: 1.0, jam: 2.0 }, // 发射档:功耗 = 射频响度,同一张表

  /* ---- 通道二 雷达:一部设备两种模式 ---- */
  LIS_REF: 600000,     // 静听参考距离 km(recv=1 听 emit=1 的照射)
  ACT_REF: 150000,     // 照射参考量程 km(emit=recv=1 打反射 1.0)
  BEACON_OPT: 1.0, BEACON_RECV: 4.0, BEACON_EMIT: 4.0, // 信标当探测器时的三个系数(它恒在照射)

  /* ---- 信号分档(信噪比档:强 = 16 倍门限通量,良 = 4 倍) ---- */
  GRADE_STRONG: 0.0625, GRADE_FAIR: 0.25,

  /* ---- 驻留积分 ---- */
  DEC_OPT: 0.90, DEC_LIS: 0.90, DEC_ACT: 0.94, // 每秒衰减率
  G_OPT: [0, 0.11, 0.15, 0.22],  // 按档增益/秒(0 无 / 1 弱 / 2 良 / 3 强)。稳态 = g/(1-DEC):1.10 / 1.50 / 2.20
  G_LIS: [0, 0.11, 0.15, 0.22],  // 静听与光学同曲线:两条都是被动 1/d^2 通道,没有理由给不同的手感
  G_ACT: [0, 0.16, 0.24, 0.32],  // 稳态 2.67 / 4.00 / 5.33;良档从零到火控级 11.2 秒(旧内核记的是"25万约 11s",量级对齐)

  /* ---- 接触等级阶梯(取值与字段名一个字不动:真相源仍是 litBlue / litRed) ---- */
  LIT1: 1.0,        // 探测级:光学【或】静听单独过门
  LIT2: 1.0,        // 识别级的交叉门:光学【与】静听都过
  LIT2_ACT: 1.5,    // 识别级的单通道门:照射建立
  LIT3: 2.0,        // 火控级:照射驻留
  ACT_DOWN: 1.5,    // 断照降级:火控是要一直端着的手电
  HYST: 0.5,        // 熄灭滞回(幽灵淡出)

  /* ---- 两个阈值:原来是散落的手抄,收进表 ---- */
  LIS_ALERT: 0.4,   // 静听方位椭圆的出圈阈值(旧模型里那个射频预警阈值的对应物)
  ACT_WARN: 0.3,    // 被照射告警阈值(原来是 21-detect 与 82-ship-icons 两份手抄的 0.3)

  /* ---- 结算节拍 ---- */
  TICK: 1.0,        // 每模拟秒一次(core/05 的 detT);解析跳步让它可以被改成别的数而不失真

  /* ---- 弹丸:常数由旧模型的可见半径反解,弹丸可见性不是本轮要改的东西 ----
     lum 反解自 旧的「标量探测半径 15万 x 探测力 0.8 x 弹丸信号系数」:
       燃烧弹 48,000 → (48000/180000)^2 = 0.0711
       冷弹   18,000 → 0.0100
       MAC    旧规则是"只有照射看得到",所以光学给一个几乎为零的 0.0005(4,025km)
     refl 保住旧的"开雷达看一切固体"语义(基准 DD 照射看得到 mac 到 150,000),
     顺带给出一个真实梯度:MAC 是致密弹芯最亮,诱饵本来就是雷达上的大亮点。 */
  PROJ: {
    mac: { lum: 0.0005, refl: 1.00 },
    mslHot: { lum: 0.0711, refl: 0.50 },
    mslCold: { lum: 0.0100, refl: 0.50 },
    inter: { lum: 0.0711, refl: 0.25 },
    decoy: { lum: 0.2500, refl: 2.00 },
    beacon: { lum: 0.0400, refl: 1.00 },
  },

  /* ---- 发射档三态:全库【唯一】的枚举。写入口是 21-detect 的 setEmit ---- */
  EMIT_MODES: ['silent', 'paint', 'jam'],
  EMIT_LABEL: { silent: '静默', paint: '照射', jam: '干扰' },
};
SENS.CLS.BB = { ...SENS.CLS.CA };  // TODO(TIER-BAL) 战列感知待标定
SENS.CLS.CV = { ...SENS.CLS.CA };  // TODO(TIER-BAL) 航母感知待标定
